#!/usr/bin/env python3
"""A 5x7 font in the PETSCII style, from BESCII (fw/font_bescii.h, CC0 1.0): each 8x8 glyph is
squeezed to 5 x 7 by removing the most redundant columns/rows (a column equal to its
neighbour goes first: the C64's doubled strokes and gaps), then fw/fonts/pet57_fixes.txt
overrides any glyph by hand. Writes fw/fonts/pet57.txt (the result, editable as ASCII art)
and fw/font_pet57.h (5 column bytes a glyph, bit 0 = top row: the SH1106 layout)."""
import os, re
here = os.path.dirname(os.path.abspath(__file__)); fw = os.path.join(here, '..')
src = open(os.path.join(fw, 'font_bescii.h')).read()
rows8 = [[int(v, 16) for v in m.group(1).split(',')] for m in re.finditer(r'\{ ([^}]*) \}', src)]
assert len(rows8) == 95

def grid(rows): return [[(r >> (7 - x)) & 1 for x in range(8)] for r in rows]
def cols_of(g): return [[g[y][x] for y in range(len(g))] for x in range(len(g[0]))]

def squeeze(g):
    # trim empty columns/rows round the glyph, keep its row position
    xs = [x for x in range(len(g[0])) if any(g[y][x] for y in range(len(g)))]
    if not xs: return [[0] * 5 for _ in range(7)]
    g = [row[min(xs):max(xs) + 1] for row in g]
    # width: drop the column most like a neighbour until 5
    while len(g[0]) > 5:
        C = cols_of(g); best = None
        for i in range(len(C)):
            score = 0
            if i > 0 and C[i] == C[i - 1]: score += 10
            if i + 1 < len(C) and C[i] == C[i + 1]: score += 10
            score -= sum(C[i])                      # prefer dropping lighter columns
            if i in (0, len(C) - 1): score -= 5      # keep the outline
            if best is None or score > best[0]: best = (score, i)
        g = [row[:best[1]] + row[best[1] + 1:] for row in g]
    w = len(g[0]); pad = (5 - w) // 2
    g = [[0] * pad + row + [0] * (5 - w - pad) for row in g]
    # height: 8 rows -> 7. Descenders (row 7 used): lift if row 0 is free, else drop a doubled row
    if any(g[7]):
        if not any(g[0]): g = g[1:]
        else:
            best = max(range(1, 7), key=lambda i: (g[i] == g[i - 1]) * 10 + (g[i] == g[i + 1]) * 10 - sum(g[i]))
            g = g[:best] + g[best + 1:]
    else:
        g = g[:7]
    return g

G = {code: squeeze(grid(rows8[code - 32])) for code in range(32, 127)}
fixes = os.path.join(fw, 'fonts', 'pet57_fixes.txt')
if os.path.exists(fixes):
    cur = None
    for line in open(fixes):
        line = line.rstrip('\n')
        if line.startswith('char '): cur = int(line[5:]); G[cur] = []
        elif cur is not None and line and set(line) <= set('.#'): G[cur].append([c == '#' for c in line])
with open(os.path.join(fw, 'fonts', 'pet57.txt'), 'w') as f:
    f.write('# PETSCII-style 5x7, derived from BESCII (CC0) by fw/tools/mkpet57.py; hand fixes in pet57_fixes.txt\n')
    for code in range(32, 127):
        f.write(f'char {code}  {chr(code)!r}\n' + '\n'.join(''.join('#' if p else '.' for p in r) for r in G[code]) + '\n')
out = ['/* GENERATED by fw/tools/mkpet57.py (PETSCII-style 5x7, from BESCII: CC0 1.0) -- do not edit */',
       '#ifndef FF_FONT_PET57_H', '#define FF_FONT_PET57_H', '#include <stdint.h>', 'static const uint8_t font_pet57[95][5] = {']
for code in range(32, 127):
    g = G[code]; assert len(g) == 7 and all(len(r) == 5 for r in g), code
    out.append('    { ' + ', '.join(f'0x{sum((1 << y) for y in range(7) if g[y][x]):02X}' for x in range(5)) + ' },   /* ' + str(code) + ' */')
out += ['};', '#endif', '']
open(os.path.join(fw, 'font_pet57.h'), 'w').write('\n'.join(out))
print('font_pet57.h written')
