#!/usr/bin/env python3
"""
Write case/board_dims.scad from gen_pcb.py's PLACEMENT constants, without regenerating
(or touching) the board. board.sh runs it after the floorplan; run it alone any time.
Only the part of gen_pcb.py above its first function is executed: constants and PLACE.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.dirname(HERE)
src = open(os.path.join(HERE, "gen_pcb.py")).read()
exec(compile(src[src.index("# ------------------------------------------------------------------ outline"):
                 src.index("def U():")], "gen_pcb.py (constants)", "exec"))
# ---- the case's numbers, from THIS placement (case/board_dims.scad is generated, never edited):
# one source, so the case cannot drift from the board. Board-relative mm, origin = the board's
# rear-left corner, +x right, +y towards the FRONT (as the PCB file).
# Pico 2 features, Pico frame (STEP +y = towards USB), from the Pico 2's STEP model (Raspberry Pi's
# Pico-2-step-20240708, MIT, "for guidance only": MEASURE a real Pico): BOOTSEL plunger centre
# (-3.50, 13.50), top z 3.50; LED centre (-5.70, 20.70), top 1.69; USB socket x +-4.0,
# y 18.87..26.80, top z 3.69. KiCad (y down) = (x_step, -y_step) at rotation 0.
CASE = os.path.join(os.path.dirname(HW), "case", "board_dims.scad")
import math  # noqa
os.makedirs(os.path.dirname(CASE), exist_ok=True)
_holes = [(x, y) for r, fp, x, y, rot in PLACE if r.startswith("H") and "M3" in fp]   # case screws only (H5-H8 hold the OLED)
_d = {
    "BOARD_W": BOARD_W, "BOARD_L": BOARD_L, "BOARD_R": CORNER_R, "BOARD_T": 1.6,
    "HOLES": _holes,
    "IEC_X": [J1_X, J2_X], "IEC_FACE_Y": -IEC_PROUD, "IEC_BODY_W": 21.4, "IEC_BODY_H": 21.4,
    "IEC_BODY_BACK_Y": round(IEC_Y + 6.72, 2),
    "USB_X": PICO_X, "USB_FACE_Y": -USB_PROUD, "USB_TOP_Z": 3.69,
    "BOOTSEL_X": round(PICO_X - 3.50, 2), "BOOTSEL_Y": round(PICO_Y - 13.50, 2), "BOOTSEL_TOP_Z": 3.50,
    "PICO_LED_X": round(PICO_X - 5.70, 2), "PICO_LED_Y": round(PICO_Y - 20.70, 2),
    "SD_X": SD_X, "SD_CARD_X": round(SD_X + SD_CARD_DX, 2), "SD_FACE_Y": BOARD_L,
    "SHAFT_X": SHAFT_X, "SHAFT_Y": SHAFT_Y,
    "LED_PWR": [D1_X + 1.27, D1_Y], "LED_ACT": [D2_X + 1.27, D2_Y],
    "OLED_X0": OLED_X0, "OLED_Y0": OLED_Y0, "OLED_W": OLED_W, "OLED_D": OLED_D,
    "BUZZER": [round(BZ_X + 2.5, 2), BZ_Y],          # body centre: pin 1 + 5.0/2 (PS1240P02BT)
    # the OLED module's support: H5-H8 (NPTH, MountingHole_2.7mm_M2.5) and the J4 header row it plugs into
    "OLED_HOLES": [(x, y) for r, fp, x, y, rot in PLACE if r in ("H5", "H6", "H7", "H8")],
    "OLED_BOARD_HOLE_D": 2.7,
    "OLED_HDR": [round(J4_X + 3.81, 2), J4_Y],      # centre of the 4-pin row (rotation 90: pins run +x)
}


def _scad(v):
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_scad(e) for e in v) + "]"
    return repr(round(v, 3)) if isinstance(v, float) else str(v)


with open(CASE, "w") as fh:
    fh.write("// GENERATED by hardware/gen/gen_pcb.py from the PCB placement -- do not edit.\n"
             "// Board-relative mm: origin = rear-left corner, +x right, +y to the FRONT.\n")
    for k_, v_ in _d.items():
        fh.write(f"{k_} = {_scad(v_)};\n")
print(f"wrote {CASE}")
