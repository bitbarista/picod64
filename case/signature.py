#!/usr/bin/env python3
"""The signature inside the front lid: pen strokes through hand-placed points (Catmull-Rom), slanted, then
drawn with a round pen. Writes signature.scad (module signature_2d(), in mm, from the left of its baseline).
    python3 case/signature.py          (needs numpy and shapely)"""
import os
import numpy as np
from shapely.geometry import LineString, Polygon, MultiPolygon
from shapely.ops import unary_union
UNIT = 3.0      # mm per x-height: capitals and loops are 3 of them
PEN = 0.6       # mm: the stroke, about the narrowest groove a 0.4 nozzle prints cleanly
SLANT = 0.32
def cr(pts, n=24):
    P = np.array(pts, float); P = np.vstack([P[0], P, P[-1]]); out = []
    for i in range(1, len(P) - 2):
        p0, p1, p2, p3 = P[i-1], P[i], P[i+1], P[i+2]
        for t in np.linspace(0, 1, n, endpoint=False):
            t2, t3 = t*t, t*t*t
            out.append(0.5*((2*p1) + (-p0+p2)*t + (2*p0-5*p1+4*p2-p3)*t2 + (-p0+3*p1-3*p2+p3)*t3))
    out.append(P[-2]); return np.array(out)
def at(dx, pts): return [(x+dx, y) for x, y in pts]
# letters, upright; x-height 1, caps 3
C  = [(2.3,2.55),(2.05,2.9),(1.5,3.05),(0.85,2.75),(0.35,2.0),(0.15,1.0),(0.35,0.25),(0.9,-0.02),(1.5,0.08),(2.0,0.45)]
a  = lambda d: at(d,[(0.75,0.82),(0.5,0.98),(0.15,0.78),(0.0,0.35),(0.15,0.02),(0.45,0.05),(0.72,0.45),(0.8,0.95),(0.72,0.45),(0.72,0.12),(0.9,0.0),(1.15,0.15)])
r  = lambda d: at(d,[(0.25,0.85),(0.35,0.98),(0.55,0.85),(0.75,0.95),(0.68,0.5),(0.65,0.1),(0.85,0.0),(1.1,0.2)])
l  = lambda d: at(d,[(0.45,1.4),(0.7,2.5),(0.65,3.05),(0.42,2.9),(0.28,2.1),(0.22,0.9),(0.28,0.12),(0.55,0.0),(0.9,0.25)])
L  = [(7.55,2.75),(7.8,3.05),(7.55,3.15),(7.2,2.7),(6.95,1.7),(6.8,0.6),(6.85,0.12),(6.6,0.02),(6.45,0.25),(6.7,0.3),(7.2,0.05),(7.75,0.0),(8.2,0.25)]
e  = lambda d: at(d,[(0.1,0.35),(0.5,0.6),(0.55,0.88),(0.32,0.95),(0.1,0.6),(0.12,0.12),(0.45,0.0),(0.8,0.2)])
c  = lambda d: at(d,[(0.5,0.98),(0.5,0.98),(0.2,0.85),(0.02,0.45),(0.1,0.05),(0.45,0.0),(0.8,0.25)])
h  = lambda d: at(d,[(0.5,1.5),(0.8,2.8),(0.72,3.35),(0.45,3.15),(0.3,2.2),(0.2,1.0),(0.12,0.0),(0.22,0.55),(0.5,0.92),(0.78,0.85),(0.82,0.45),(0.85,0.08),(1.3,0.02),(2.0,0.15),(2.6,0.4)])
w1 = C + a(2.0) + r(3.1) + l(4.1)
w2 = L + e(8.1) + a(8.95) + c(10.1) + h(11.0)
strokes = [w1, w2]

lines = []
for s in strokes:
    p = cr(s) * UNIT; p[:, 0] += SLANT * p[:, 1]; lines.append(LineString(p))
shape = unary_union([ln.buffer(PEN / 2, quad_segs=8) for ln in lines]).simplify(0.01)
x0 = shape.bounds[0]
pts, paths = [], []
for g in (shape.geoms if isinstance(shape, MultiPolygon) else [shape]):
    for ring in [g.exterior] + list(g.interiors):
        c = list(ring.coords)[:-1]
        paths.append(list(range(len(pts), len(pts) + len(c)))); pts += [(x - x0, y) for x, y in c]
b = shape.bounds
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "signature.scad"), "w") as f:
    f.write("// GENERATED by signature.py. Do not edit; change the strokes there and rerun it.\n")
    f.write("SIG_W = %.2f; SIG_DESC = %.2f; SIG_H = %.2f;   // its width, below and above the baseline (mm)\n" % (b[2] - b[0], -b[1], b[3]))
    f.write("module signature_2d() polygon(points = [%s],\n    paths = [%s]);\n" % (
        ",".join("[%.3f,%.3f]" % p for p in pts), ",".join("[" + ",".join(map(str, q)) + "]" for q in paths)))
print("signature: %.1f x %.1f mm, %d points" % (b[2] - b[0], b[3] - b[1], len(pts)))
