#!/usr/bin/env python3
"""fw/fonts/bescii/Bescii-Mono.ttf (BESCII v2.0, Damian Vila, CC0 1.0) -> fw/font_bescii.h:
95 glyphs (ASCII 32-126), 8 row bytes each, bit 7 = leftmost pixel. The font is drawn on an
8 x 8 pixel grid, so at 8 px it rasterises exactly (checked: no pixel outside the cell)."""
import os
from PIL import ImageFont, Image, ImageDraw
here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype(os.path.join(here, '..', 'fonts', 'bescii', 'Bescii-Mono.ttf'), 8)
out = ['/* GENERATED by fw/tools/mkbescii.py from BESCII v2.0 (Damian Vila, CC0 1.0,',
       ' * fw/fonts/bescii/LICENCE) -- do not edit */',
       '#ifndef FF_FONT_BESCII_H', '#define FF_FONT_BESCII_H', '#include <stdint.h>',
       'static const uint8_t font_bescii[95][8] = {']
for code in range(32, 127):
    im = Image.new('1', (16, 16), 0); d = ImageDraw.Draw(im); d.fontmode = '1'
    d.text((0, 0), chr(code), font=font, fill=1)
    for y in range(16):
        for x in range(16):
            assert not (im.getpixel((x, y)) and (x >= 8 or y >= 8)), (chr(code), x, y)
    rows = [sum(0x80 >> x for x in range(8) if im.getpixel((x, y))) for y in range(8)]
    out.append('    { ' + ', '.join(f'0x{r:02X}' for r in rows) + ' },   /* ' + str(code) + ' */')
out += ['};', '#endif', '']
open(os.path.join(here, '..', 'font_bescii.h'), 'w').write('\n'.join(out))
print('font_bescii.h: 95 glyphs')
