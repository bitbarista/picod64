#!/bin/bash
# Measure the label font's glyphs and write label_glyphs.scad (GLYPH_FONT, CAP, I_STEM, GLYPH_X for ASCII 33-126).
# The lid labels are tracked glyph by glyph (picod64-case.scad, label_2d), so they need each glyph's ink extent.
# Run it after changing LABEL_FONT:   bash case/gen_glyphs.sh "Font Name"      (default: Eurostile)
# then bash case/check_labels.sh: a new font can leave islands or gaps too small to print.
set -e; cd "$(dirname "$0")"; FONT=${1:-Eurostile}; T=$(mktemp -d); S=100   # measured at size 100, stored per unit size
fc-match "$FONT" | grep -qi "$(echo "$FONT" | cut -d: -f1)" || { echo "font '$FONT' is not installed (fc-match: $(fc-match "$FONT"))"; exit 1; }
printf 'for (c = [33 : 126]) translate([((c - 33) %% 10) * 250, -floor((c - 33) / 10) * 250]) text(chr(c), size = %s, font = "%s", halign = "left");\n' $S "$FONT" > $T/g.scad
openscad -o $T/g.svg $T/g.scad 2>/dev/null
python3 - $T/g.svg "$FONT" $S > label_glyphs.scad <<'PY'
import re, sys
svg, font, S = sys.argv[1], sys.argv[2], float(sys.argv[3])
box = {}                                   # code -> [x0, x1, y0, y1] in glyph coords; i: its lower part's top too
subs = {}
for d in re.findall(r'd="([^"]+)"', open(svg).read()):
    for sub in re.split(r'[Mm]', d):
        pts = [tuple(map(float, p.split(','))) for p in re.findall(r'-?[\d.]+,-?[\d.]+', sub)]
        if len(pts) < 3: continue
        xs = [p[0] for p in pts]; ys = [-p[1] for p in pts]   # SVG y is down
        col = int(((min(xs) + max(xs)) / 2 + 50) // 250)          # by centre, half a pitch either way: descenders and
        row = int((125 - (min(ys) + max(ys)) / 2) // 250)          # negative bearings stay in their own cell; small
        c = 33 + row * 10 + col; ox = col * 250; oy = -row * 250                                        # coords keep 0.01 precision
        ys = [y - oy for y in ys]
        b = box.setdefault(c, [1e9, -1e9, 1e9, -1e9])
        b[0] = min(b[0], min(xs) - ox); b[1] = max(b[1], max(xs) - ox); b[2] = min(b[2], min(ys)); b[3] = max(b[3], max(ys))
        subs.setdefault(c, []).append((min(ys), max(ys)))
r = lambda v: f"{v / S:.4f}"
cap = box[ord('I')][3]
lower = [s for s in subs[ord('i')] if s[0] < 1]               # the stem (starts at the baseline); the dot is above it
print(f'// GENERATED by gen_glyphs.sh from the installed "{font}". Do not edit; rerun it after changing LABEL_FONT.')
print(f'GLYPH_FONT = "{font}";')
print(f'CAP = {r(cap)};          // cap height (I) / size: labels are centred on it, so one baseline per label')
print(f'I_STEM = {r(max(s[1] for s in lower))};       // i stem top / size: the dot is trimmed clear of it (I_DOT_GAP)')
print('// [char, ink x0, ink x1] per unit size')
rows = [f'[{chr(c)!r}, {r(b[0])}, {r(b[1])}]'.replace("'\\\\'", '"\\\\"').replace("'\"'", '"\\""') for c, b in sorted(box.items())]
rows = [x if not x.startswith("['") else '["' + x[2:].split("',", 1)[0] + '",' + x[2:].split("',", 1)[1] for x in rows]
print('GLYPH_X = [' + ',\n           '.join(', '.join(rows[i:i + 6]) for i in range(0, len(rows), 6)) + '];')
PY
rm -rf $T; echo "label_glyphs.scad written for $FONT"
