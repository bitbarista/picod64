#!/bin/sh
# Assemble the browser and make browser_prg.h, which the firmware embeds. The header is committed,
# so building the firmware does not need ACME; run this after changing browser.asm.
#   sh fw/browser/build.sh
set -e
cd "$(dirname "$0")"
acme browser.asm
acme boot.asm
python3 - <<'PY'
with open("browser_prg.h", "w") as f:
    f.write("/* GENERATED by fw/browser/build.sh from browser.asm and boot.asm. Do not edit. */\n")
    f.write("#ifndef BROWSER_PRG_H\n#define BROWSER_PRG_H\n#include <stdint.h>\n")
    for name, sym in (("browser.prg", "browser_prg"), ("boot.prg", "browser_boot")):
        d = open(name, "rb").read()
        assert d[:2] == b"\x01\x08", "not at $0801"
        f.write("static const uint8_t %s[%d] = {\n" % (sym, len(d)))
        for i in range(0, len(d), 20):
            f.write("    " + ",".join("0x%02X" % b for b in d[i:i + 20]) + ",\n")
        f.write("};\n")
        print("%s: %d bytes" % (name, len(d)))
    f.write("#endif\n")
PY
