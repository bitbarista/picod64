#!/usr/bin/env python3
"""Cycle-by-cycle bus comparison: core/cpu6502.h against perfect6502 [S4].

    python3 -I host/diff.py [--seed N] [--blocks N] [--cases N]

Each case is a random program: blocks that load random A/X/Y/P (D included)
then run one opcode with random operands that point at random data. Both
models run it; the traces are aligned on the first opcode fetch at $0400 and
every cycle's (address, R/W, data) must match.

perfect6502 is a cycle-trace build of it, run as a black
box. Override with P6502_TRACE=/path/to/trace.

⚠ Excluded opcodes, and why:
  - ANC/ALR/ARR ($0B $2B $4B $6B): perfect6502 is wrong on them.
  - LAS ($BB): perfect6502 leaves S alone; 64doc [S3], Vardy [S6] and the 1541 Testsuite's pc64-lasay
    (passes on the twin, and in VICE as a black box) have S = M & S, as the core does (2026-11-09).
  - ANE, SHA, SHX, SHY, SHS ($8B $93 $9F $9E $9C $9B) are compared since 2026-11-09: bus-identical.
  - LXA ($AB): its constant differs between chips, so only where it can't matter: #$00 (as a
    demo's loader uses it, 2026-11-06), or A = $FF first.
  - KIL/JAM: stop the CPU.
  - control flow (JMP/JSR/RTS/RTI/BRK) and branches are generated by hand below,
    not at random, so they stay inside the program.
"""
import os, random, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
P6502 = os.environ.get("P6502_TRACE",
        os.path.expanduser("~/tools/tests/p6502-trace"))
CORE = os.path.join(HERE, "cpu_test")

JAM = {0x02, 0x12, 0x22, 0x32, 0x42, 0x52, 0x62, 0x72, 0x92, 0xB2, 0xD2, 0xF2}
UNSTABLE_OR_TODO = {0x6B, 0xBB}   # ARR: P6502_WRONG as well; LAS: above
P6502_WRONG = {0x0B, 0x2B, 0x4B, 0x6B}
FLOW = {0x00, 0x20, 0x40, 0x4C, 0x60, 0x6C} | {0x10, 0x30, 0x50, 0x70, 0x90, 0xB0, 0xD0, 0xF0}
STACK = {0x9A}   # TXS would move the stack onto random data; tested via TSX/push/pull

# operand length by low bits, from the opcode matrix [S1][S6]
def oplen(op):
    if op in (0x20, 0x4C, 0x6C): return 3
    lo = op & 0x1F
    if lo in (0x0C, 0x0D, 0x0E, 0x0F, 0x19, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F): return 3
    if lo in (0x00,) and op & 0x80 == 0: return 1 if op in (0x40, 0x60) else (2 if op == 0x00 else 1)
    if lo in (0x08, 0x0A, 0x18, 0x1A): return 1
    return 2

CODE, DATA_LO, DATA_HI = 0x0400, 0x4000, 0x7FFF
RANDOM = [o for o in range(256) if o not in JAM | UNSTABLE_OR_TODO | P6502_WRONG | FLOW | STACK]
if os.environ.get("DIFF_OPS"):   # DIFF_OPS=9F,93: only these, e.g. to check ones excluded above
    RANDOM = [int(o, 16) for o in os.environ["DIFF_OPS"].split(",")]

def build(rng, nblocks):
    mem = [rng.randrange(256) for _ in range(65536)]
    # zero page holds pointers into the data area, so (zp,X) and (zp),Y land there
    for i in range(0, 256, 2):
        p = rng.randrange(DATA_LO, DATA_HI - 0x200)
        mem[i], mem[i + 1] = p & 0xFF, p >> 8
    code = []
    def emit(*b): code.extend(b)
    sub = 0x3F00          # JSR target: a lone RTS
    mem[sub] = 0x60
    irq = 0x3F10          # BRK handler: RTI
    mem[irq] = 0x40
    mem[0xFFFE], mem[0xFFFF] = irq & 0xFF, irq >> 8
    # ⚠ S after reset is not defined on real silicon; perfect6502 leaves $BD,
    # the core $FD. Programs set it, as real code does: LDX #$FF; TXS.
    emit(0xA2, 0xFF, 0x9A)
    for _ in range(nblocks):
        x = rng.randrange(256)
        emit(0xA2, x, 0xA0, rng.randrange(256))                    # LDX/LDY #
        kind = rng.random()
        op = rng.choice(RANDOM)
        z = rng.randrange(256)
        # ⚠ Earlier blocks' zero-page stores overwrite pointers, and an
        # indirect store through a corrupted one landed in the code. Indirect
        # ops get their pointer written immediately before them.
        if op & 0x1F in (0x01, 0x03, 0x11, 0x13):
            loc = (z + x) & 0xFF if op & 0x1F in (0x01, 0x03) else z
            p = rng.randrange(DATA_LO, DATA_HI - 0x200)
            emit(0xA9, p & 0xFF, 0x85, loc, 0xA9, p >> 8, 0x85, (loc + 1) & 0xFF)
        emit(0xA9, rng.randrange(256) | 0x20, 0x48, 0x28)          # LDA #p; PHA; PLP (I may be set)
        emit(0xA9, rng.randrange(256))                             # LDA #
        if op in (0x93, 0x9F, 0x9E, 0x9C, 0x9B):                    # SHA/SHX/SHY/SHS: a page cross stores at (value << 8), so
            emit(0x09, 0x40, 0xA2, x | 0x40, 0xA0, rng.randrange(256) | 0x40)   # bit 6 of A, X, Y keeps it in the data
                                                                   # (it hit the code and a JAM, 2026-11-09)
        if kind < 0.08:
            emit(0x20, sub & 0xFF, sub >> 8)                       # JSR / RTS
        elif kind < 0.12:
            emit(0x00, 0xEA)                                       # BRK / RTI
        elif kind < 0.16:
            # JMP (ind) to the next block; a third of pointers sit at $xxFF,
            # where the high byte comes from $xx00, not the next page [S1][S3]
            ptr = rng.randrange(DATA_LO, DATA_HI - 0x100)
            if rng.random() < 0.33: ptr |= 0xFF
            hiloc = (ptr & 0xFF00) | ((ptr + 1) & 0xFF)
            tgt = CODE + len(code) + 10 + 3
            emit(0xA9, tgt & 0xFF, 0x8D, ptr & 0xFF, ptr >> 8,
                 0xA9, tgt >> 8, 0x8D, hiloc & 0xFF, hiloc >> 8, 0x6C, ptr & 0xFF, ptr >> 8)
        elif kind < 0.30:
            op = rng.choice([0x10, 0x30, 0x50, 0x70, 0x90, 0xB0, 0xD0, 0xF0])
            k = rng.randrange(0, 12)
            emit(op, k, *([0xEA] * k))                            # lands inside the NOP pad
        else:
            n = oplen(op)
            if op == 0xAB:                                         # LXA: #$00, or A = $FF first
                if rng.random() < 0.5: z = 0
                else: emit(0xA9, 0xFF)
            if n == 2:
                emit(op, z)
                if op == 0xAB:                                     # its A and X onto the bus, before the next block reloads X
                    a = rng.randrange(DATA_LO, DATA_HI - 0x100)
                    emit(0x8E, a & 0xFF, a >> 8, 0x8D, (a + 1) & 0xFF, (a + 1) >> 8)
            elif n == 3:
                a = rng.randrange(DATA_LO, DATA_HI - 0x100)
                emit(op, a & 0xFF, a >> 8)
            else: emit(op)
        if len(code) > 0x3A00: break
    here = CODE + len(code)
    emit(0x4C, CODE & 0xFF, CODE >> 8)                             # loop
    mem[CODE:CODE + len(code)] = code
    mem[0xFFFC], mem[0xFFFD] = CODE & 0xFF, CODE >> 8
    return mem

RETRIES = []

def run(cmd):
    # ⚠ perfect6502 sometimes dies on an assert in netlist_sim.c getGroupValue()
    # and the SAME input then passes when rerun (seen 2026-10-25, 2 runs in 3
    # of 400 cases). It is the oracle's flake, not a verdict: rerun it, and
    # report every rerun so the count stays visible.
    for attempt in range(3):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode == 0:
            return [tuple(l.split()[1:4]) for l in r.stdout.splitlines() if l.strip()]
        RETRIES.append((os.path.basename(cmd[0]), r.returncode))
    raise SystemExit(f"{cmd[0]} failed 3 times (rc {r.returncode})")

def main():
    args = sys.argv[1:]
    seed = int(args[args.index("--seed") + 1]) if "--seed" in args else 1
    blocks = int(args[args.index("--blocks") + 1]) if "--blocks" in args else 60
    cases = int(args[args.index("--cases") + 1]) if "--cases" in args else 20
    cycles = blocks * 16
    total = 0
    for case in range(cases):
        rng = random.Random(seed * 1000 + case)
        mem = build(rng, blocks)
        with tempfile.NamedTemporaryFile("w", suffix=".hex", delete=False) as f:
            f.write("\n".join(f"{b:02x}" for b in mem) + "\n")
            path = f.name
        try:
            gold = run([P6502, path, str(cycles + 40)])
            mine = run([CORE, "trace", path, str(cycles)])
        finally:
            os.unlink(path)
        # align: perfect6502 runs its reset sequence first [S4]
        start = next(i for i, (a, rw, d) in enumerate(gold) if a == "0400" and rw == "1")
        gold = gold[start:]
        n = min(len(gold), len(mine))
        if n < cycles * 0.9:
            print(f"case {case}: only {n} comparable cycles"); return 1
        for i in range(n):
            if gold[i] != mine[i]:
                print(f"case {case} (seed {seed}): MISMATCH at cycle {i}")
                for j in range(max(0, i - 12), min(n, i + 4)):
                    mark = "  <==" if j == i else ""
                    print(f"  {j:6d}  p6502 {' '.join(gold[j])}   core {' '.join(mine[j])}{mark}")
                return 1
        total += n
        print(f"case {case}: {n} cycles identical")
    if RETRIES: print(f"note: {len(RETRIES)} oracle rerun(s) after a crash: {RETRIES}")
    print(f"PASS: {cases} cases, {total} cycles, bus-identical to perfect6502")
    return 0

if __name__ == "__main__":
    sys.exit(main())
