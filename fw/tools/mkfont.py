#!/usr/bin/env python3
"""fw/font5x7.txt (PicoD64's own 5x7 glyphs, ASCII art) -> fw/font5x7.h:
5 column bytes per glyph, bit 0 = top row (the SH1106's page layout, datasheet v2.3)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
G, cur = {}, None
for line in open(os.path.join(here, 'font5x7.txt')):
    line = line.rstrip('\n')
    if not line or line.startswith('#') and not set(line) <= set('.#'):
        continue
    if line.startswith('char '):
        cur = int(line[5:]); G[cur] = []
    else:
        G[cur].append(line)
assert sorted(G) == list(range(32, 127)), 'need 95 glyphs, space to ~'
out = ["/* GENERATED by fw/tools/mkfont.py from font5x7.txt (PicoD64's own glyphs) -- do not edit */",
       '#ifndef FF_FONT5X7_H', '#define FF_FONT5X7_H', '#include <stdint.h>', 'static const uint8_t font5x7[95][5] = {']
for code in range(32, 127):
    rows = G[code]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), code
    cols = [sum(1 << y for y in range(7) if rows[y][x] == '#') for x in range(5)]
    out.append('    { ' + ', '.join(f'0x{v:02X}' for v in cols) + ' },   /* ' + str(code) + ' */')
out += ['};', '#endif', '']
open(os.path.join(here, '..', 'font5x7.h'), 'w').write('\n'.join(out))
# the same glyphs as a file for the SD card (fw/ui.h, UI_FONT57_SIZE)
blob = bytes(sum(1 << y for y in range(7) if G[code][y][x] == '#') for code in range(32, 127) for x in range(5))
assert len(blob) == 475
open(os.path.join(here, '..', 'fonts', 'font5x7.bin'), 'wb').write(blob)
print('font5x7.h, fonts/font5x7.bin:', len(G), 'glyphs')

